/*
New file: backend/test/critical/exchange-rate-history.spec.ts
Pins exchange rate history (INV-EXCHANGE-RATE-HISTORY).

THE GAP: upsertCurrency overwrote the single
currency_exchange_rates row in place. The rate a cheque,
revaluation, or report was booked at vanished the moment a new
rate was saved — no audit trail, no as-of conversion.

THE FIX: migration 2040000000270 adds the append-only
currency_exchange_rate_history table, backfills one row per live
rate, and installs a trigger that records every genuine rate/base
change from every writer (upsert, revaluation closing-rate
update, seed). exchangeRateAsOf reads the rate registered at a
moment and fails closed when none was registered yet.

WHAT THIS PINS on PGlite, driving the REAL migration up/down
and the REAL exchangeRateAsOf:
- insert USD 48 -> one history row at 48.
- update to 50 -> second row at 50; as-of between them -> 48,
  as-of at/after the second -> 50.
- name-only update -> no new history row.
- as-of before the first row -> rejected.
- backfill: a pre-existing EUR row with no history seeds one
  row at its updated_at on up.
- down removes the table, the triggers, and the function.
*/

import 'reflect-metadata';
import { strict as assert } from 'node:assert';
import { PGlite } from '@electric-sql/pglite';
import { Kysely } from 'kysely';
import { PGliteDialect } from 'kysely-pglite-dialect';
import { Database } from '../../src/database/database.types';
import { exchangeRateAsOf } from '../../src/modules/accounting/exchange-rate-history';
import { up, down } from '../../src/database/migrations/2040000000270_exchange_rate_history';

async function historyRows(pg: PGlite, tenant: string, code: string): Promise<Array<{ exchange_rate: string; effective_from: Date }>> {
  const res = await pg.query<{ exchange_rate: string; effective_from: Date }>(
    `SELECT exchange_rate, effective_from FROM currency_exchange_rate_history WHERE tenant_id = $1 AND currency_code = $2 ORDER BY id`,
    [tenant, code],
  );
  return res.rows;
}

async function main(): Promise<void> {
  const pg = new PGlite();
  const db = new Kysely<Database>({ dialect: new PGliteDialect(pg) });

  try {
    await pg.exec(`
      CREATE TABLE currency_exchange_rates (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        tenant_id TEXT NOT NULL DEFAULT '', account_id TEXT NOT NULL DEFAULT '',
        currency_code TEXT NOT NULL, currency_name TEXT NOT NULL,
        exchange_rate NUMERIC(15, 6) NOT NULL DEFAULT 1,
        is_base BOOLEAN NOT NULL DEFAULT FALSE, symbol TEXT NOT NULL DEFAULT '',
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        CONSTRAINT uq_tenant_currency UNIQUE (tenant_id, currency_code)
      );
      INSERT INTO currency_exchange_rates (tenant_id, currency_code, currency_name, exchange_rate, is_base, updated_at)
        VALUES ('t1','EUR','Euro',52,false,'2026-10-01 10:00:00+00');
    `);

    await up(db as never);

    // Backfill seeded the pre-existing EUR row.
    const eur = await historyRows(pg, 't1', 'EUR');
    assert.equal(eur.length, 1);
    assert.equal(Number(eur[0].exchange_rate), 52);
    assert.equal(await exchangeRateAsOf(db, 't1', 'EUR', '2026-10-02'), 52);
    await assert.rejects(exchangeRateAsOf(db, 't1', 'EUR', '2026-09-01'), /No exchange rate was registered/);

    // Trigger: insert, genuine update, name-only update.
    await pg.exec(`INSERT INTO currency_exchange_rates (tenant_id, currency_code, currency_name, exchange_rate) VALUES ('t1','USD','Dollar',48)`);
    await pg.exec(`UPDATE currency_exchange_rates SET exchange_rate = 50, updated_at = NOW() WHERE tenant_id = 't1' AND currency_code = 'USD'`);
    const usd = await historyRows(pg, 't1', 'USD');
    assert.equal(usd.length, 2);
    assert.equal(Number(usd[0].exchange_rate), 48);
    assert.equal(Number(usd[1].exchange_rate), 50);

    const first = usd[0].effective_from;
    const second = usd[1].effective_from;
    assert.equal(await exchangeRateAsOf(db, 't1', 'USD', first), 48);
    assert.equal(await exchangeRateAsOf(db, 't1', 'USD', new Date(second.getTime() - 1)), 48);
    assert.equal(await exchangeRateAsOf(db, 't1', 'USD', second), 50);
    await assert.rejects(exchangeRateAsOf(db, 't1', 'USD', new Date(first.getTime() - 1)), /No exchange rate was registered/);

    await pg.exec(`UPDATE currency_exchange_rates SET currency_name = 'US Dollar' WHERE tenant_id = 't1' AND currency_code = 'USD'`);
    assert.equal((await historyRows(pg, 't1', 'USD')).length, 2);

    await down(db as never);
    const tables = await pg.query(`SELECT 1 FROM pg_tables WHERE tablename = 'currency_exchange_rate_history'`);
    assert.equal(tables.rows.length, 0);
    const funcs = await pg.query(`SELECT 1 FROM pg_proc WHERE proname = 'record_currency_exchange_rate_history'`);
    assert.equal(funcs.rows.length, 0);

    console.log('Exchange rate history tests passed.');
  } finally {
    await db.destroy();
  }
}

main().then(
  () => process.exit(0),
  (error) => {
    console.error(error);
    process.exit(1);
  },
);
