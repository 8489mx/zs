function translateValue(val, targetLang, keyName) {
  if (typeof val !== 'string') return val;
  const dict = DICTIONARIES[targetLang] || {};
  
  // Exact match from vocabulary
  if (dict[val]) return dict[val];

  // Try substring replacement for common components
  let translated = val;
  for (const [enTerm, targetTerm] of Object.entries(dict)) {
    if (translated === enTerm) return targetTerm;
  }

  // Fallback to English if no translation available yet
  return val;
}

function deepTranslate(sourceObj, targetLang) {
  const result = {};
  for (const [key, val] of Object.entries(sourceObj)) {
    if (typeof val === 'object' && val !== null && !Array.isArray(val)) {
      result[key] = deepTranslate(val, targetLang);
    } else {
      result[key] = translateValue(val, targetLang, key);
    }
  }
  return result;
}

function generateLanguage(langCode) {
  console.log(`Generating locale for [${langCode}]...`);
  const translated = deepTranslate(en, langCode);
  const outPath = path.join(LOCALES_DIR, `${langCode}.json`);
  fs.writeFileSync(outPath, JSON.stringify(translated, null, 2), 'utf8');
  console.log(`Saved: ${outPath} (${Object.keys(translated).length} top-level categories)`);
}

