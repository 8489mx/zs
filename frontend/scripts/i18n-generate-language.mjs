let targetLangs = ['zh', 'bn', 'ur', 'hi', 'tl', 'fr'];

const langArg = args.find(a => a.startsWith('--lang='));
if (langArg) {
  const code = langArg.split('=')[1].trim();
  targetLangs = [code];
}

for (const code of targetLangs) {
  generateLanguage(code);
}

