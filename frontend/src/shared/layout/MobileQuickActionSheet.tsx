export function MobileQuickActionSheet({ isOpen, onClose }: MobileQuickActionSheetProps) {
  const navigate = useNavigate();
  const [quickProductOpen, setQuickProductOpen] = useState(false);
  const [priceCheckerOpen, setPriceCheckerOpen] = useState(false);

  const tenant = useAuthStore((state) => state.tenant);
  const { data: settings } = useSettingsQuery();

  const currentVertical = resolveCurrentVertical(tenant, settings);
  const quickActions = getMobileQuickActionsConfig(currentVertical, settings);

  const handleActionClick = (action: MobileQuickActionItem) => {
    triggerHaptic('selection');
    onClose();

    if (action.actionKey === 'priceChecker') {
      triggerHaptic('medium');
      setPriceCheckerOpen(true);
      return;
    }

    if (action.actionKey === 'quickProduct') {
      setQuickProductOpen(true);
      return;
    }

    if (action.to) {
      navigate(action.to);
    }
  };

  return (
    <>
      <DialogShell
        open={isOpen}
        onClose={onClose}
        width="min(440px, 94vw)"
        shellClassName="mobile-quick-action-dialog"
      >
        <div className="mobile-quick-action-sheet" dir="rtl">
          <div className="mobile-quick-action-header">
            <div className="mobile-quick-action-handle" />
            <h3 className="mobile-quick-action-title">إجراءات سريعة</h3>
            <p className="mobile-quick-action-sub">اختر الإجراء الذي تريد تنفيذه فوراً</p>
          </div>

          <div className="mobile-quick-action-grid">
            {quickActions.map((action) => (
              <button
                key={action.id}
                type="button"
                className="mobile-quick-action-btn"
                onClick={() => handleActionClick(action)}
              >
                <div
                  className="mobile-quick-action-icon"
                  style={{ backgroundColor: action.bg, color: action.color }}
                >
                  {renderQuickActionIcon(action.iconType)}
                </div>
                <div className="mobile-quick-action-text">
                  <strong>{action.title}</strong>
                  <span>{action.subtitle}</span>
                </div>
              </button>
            ))}
          </div>
        </div>
      </DialogShell>

      {quickProductOpen && (
        <QuickProductModal
          isOpen={quickProductOpen}
          onClose={() => setQuickProductOpen(false)}
          itemType="product"
          onSuccess={() => {
            setQuickProductOpen(false);
          }}
        />
      )}

      {priceCheckerOpen && (
        <PriceStockCheckerModal
          isOpen={priceCheckerOpen}
          onClose={() => setPriceCheckerOpen(false)}
        />
      )}
    </>
  );
}
