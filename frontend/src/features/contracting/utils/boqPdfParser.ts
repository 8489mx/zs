interface ScoredCandidateHeader {
  lineIndex: number;
  score: number;
  detectedColumns: { field: keyof ColumnMapping; item: PdfTextItem; headerText: string }[];
}

export function detectPdfTableHeaders(lines: PdfLine[]): {
  headerLineIdx: number;
  columnBoundaries: DetectedColumnBoundary[];
  mapping: ColumnMapping;
  headers: string[];
} {
  let bestCandidate: ScoredCandidateHeader | null = null;

  // Scan early lines (first 40 lines) to find the table header row
  const scanLimit = Math.min(lines.length, 40);

  for (let idx = 0; idx < scanLimit; idx++) {
    const line = lines[idx];
    if (line.items.length < 2) continue;

    let score = 0;
    const detected: { field: keyof ColumnMapping; item: PdfTextItem; headerText: string }[] = [];
    const usedFields = new Set<keyof ColumnMapping>();

    for (const it of line.items) {
      const clean = fixVisualArabicIfNeeded(it.str).trim();
      if (!clean) continue;

      // Match against aliases
      if (!usedFields.has('descriptionCol') && testCellMatches(clean, COLUMN_ALIASES.description)) {
        detected.push({ field: 'descriptionCol', item: it, headerText: clean });
        usedFields.add('descriptionCol');
        score += 6;
      } else if (!usedFields.has('qtyCol') && testCellMatches(clean, COLUMN_ALIASES.quantity)) {
        detected.push({ field: 'qtyCol', item: it, headerText: clean });
        usedFields.add('qtyCol');
        score += 5;
      } else if (
        !usedFields.has('unitPriceCol') &&
        testCellMatches(clean, COLUMN_ALIASES.unitPrice) &&
        !testCellMatches(clean, COLUMN_ALIASES.totalPrice)
      ) {
        detected.push({ field: 'unitPriceCol', item: it, headerText: clean });
        usedFields.add('unitPriceCol');
        score += 5;
      } else if (!usedFields.has('unitCol') && testCellMatches(clean, COLUMN_ALIASES.unit)) {
        detected.push({ field: 'unitCol', item: it, headerText: clean });
        usedFields.add('unitCol');
        score += 4;
      } else if (!usedFields.has('itemCodeCol') && testCellMatches(clean, COLUMN_ALIASES.itemCode)) {
        detected.push({ field: 'itemCodeCol', item: it, headerText: clean });
        usedFields.add('itemCodeCol');
        score += 3;
      } else if (!usedFields.has('totalPriceCol') && testCellMatches(clean, COLUMN_ALIASES.totalPrice)) {
        detected.push({ field: 'totalPriceCol', item: it, headerText: clean });
        usedFields.add('totalPriceCol');
        score += 3;
      } else if (!usedFields.has('estimatedCostCol') && testCellMatches(clean, COLUMN_ALIASES.estimatedCost)) {
        detected.push({ field: 'estimatedCostCol', item: it, headerText: clean });
        usedFields.add('estimatedCostCol');
        score += 2;
      } else if (!usedFields.has('categoryCol') && testCellMatches(clean, COLUMN_ALIASES.category)) {
        detected.push({ field: 'categoryCol', item: it, headerText: clean });
        usedFields.add('categoryCol');
        score += 2;
      } else if (!usedFields.has('notesCol') && testCellMatches(clean, COLUMN_ALIASES.notes)) {
        detected.push({ field: 'notesCol', item: it, headerText: clean });
        usedFields.add('notesCol');
        score += 1;
      }
    }

    if (score >= 8 && (!bestCandidate || score > bestCandidate.score)) {
      bestCandidate = { lineIndex: idx, score, detectedColumns: detected };
    }
  }

  // Fallback: If no standard header line found, construct reasonable default intervals
  if (!bestCandidate || bestCandidate.detectedColumns.length < 2) {
    const defaultHeaders = [
      'رقم البند (Item Code)',
      'بيان الأعمال والمواصفات (Description)',
      'الوحدة (Unit)',
      'الكمية (Qty)',
      'الفئة (Rate)',
      'الإجمالي (Total)',
    ];
    const defaultMapping: ColumnMapping = {
      itemCodeCol: 0,
      descriptionCol: 1,
      unitCol: 2,
      qtyCol: 3,
      unitPriceCol: 4,
      totalPriceCol: 5,
      categoryCol: -1,
      estimatedCostCol: -1,
      notesCol: -1,
    };
    return {
      headerLineIdx: -1,
      columnBoundaries: [],
      mapping: defaultMapping,
      headers: defaultHeaders,
    };
  }

  // Sort detected columns by their center X ascending (left to right)
  const sortedColumns = bestCandidate.detectedColumns
    .map((c) => ({
      field: c.field,
      headerText: c.headerText,
      x: c.item.x,
      width: c.item.width || 20,
      xCenter: c.item.x + (c.item.width || 20) / 2,
    }))
    .sort((a, b) => a.xCenter - b.xCenter);

  // Compute non-overlapping contiguous boundaries between adjacent columns
  // Description column is wide, so narrow columns (itemCode, unit, etc.) use their outer margins
  const descIdx = sortedColumns.findIndex((c) => c.field === 'descriptionCol');
  const columnBoundaries: DetectedColumnBoundary[] = [];

  for (let i = 0; i < sortedColumns.length; i++) {
    const cur = sortedColumns[i];
    let minX = 0;
    let maxX = 999999;

    if (descIdx !== -1) {
      if (i < descIdx) {
        minX = i === 0 ? 0 : (sortedColumns[i - 1].xCenter + cur.xCenter) / 2;
        if (i === descIdx - 1) {
          maxX = Math.max(cur.x + cur.width + 12, (cur.xCenter + sortedColumns[descIdx].xCenter) / 2);
        } else {
          maxX = (cur.xCenter + sortedColumns[i + 1].xCenter) / 2;
        }
      } else if (i === descIdx) {
        minX = i === 0 ? 0 : columnBoundaries[i - 1].maxX;
        if (i < sortedColumns.length - 1) {
          const next = sortedColumns[i + 1];
          // Protect wide description: right boundary extends close to the narrow column's left edge
          maxX = Math.max(cur.x + cur.width, next.x - 12);
        } else {
          maxX = 999999;
        }
      } else {
        // i > descIdx (e.g. itemCode on the right in RTL)
        minX = columnBoundaries[i - 1].maxX;
        maxX = i === sortedColumns.length - 1 ? 999999 : (cur.xCenter + sortedColumns[i + 1].xCenter) / 2;
      }
    } else {
      minX = i === 0 ? 0 : (sortedColumns[i - 1].xCenter + cur.xCenter) / 2;
      maxX = i === sortedColumns.length - 1 ? 999999 : (cur.xCenter + sortedColumns[i + 1].xCenter) / 2;
    }

    columnBoundaries.push({
      field: cur.field,
      headerText: cur.headerText,
      xCenter: cur.xCenter,
      minX,
      maxX,
    });
  }

  // Build column mapping indices based on left-to-right order in matrix
  const mapping: ColumnMapping = {
    itemCodeCol: -1,
    descriptionCol: -1,
    categoryCol: -1,
    unitCol: -1,
    qtyCol: -1,
    unitPriceCol: -1,
    estimatedCostCol: -1,
    notesCol: -1,
    totalPriceCol: -1,
  };

  const headers: string[] = [];
  for (let colIdx = 0; colIdx < columnBoundaries.length; colIdx++) {
    const col = columnBoundaries[colIdx];
    mapping[col.field] = colIdx;
    headers.push(col.headerText);
  }

  return {
    headerLineIdx: bestCandidate.lineIndex,
    columnBoundaries,
    mapping,
    headers,
  };
}

