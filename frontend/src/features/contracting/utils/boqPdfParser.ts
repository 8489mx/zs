/**
 * Normalizes unicode representation forms and corrects reversed visual Arabic
 * generated by legacy PDF engines (AutoCAD / Crystal Reports).
 */
export function fixVisualArabicIfNeeded(text: string): string {
  if (!text) return '';
  const normalized = normalizeArabicDigits(text.normalize('NFKC'));

  const words = normalized.trim().split(/\s+/);
  let reversedSignals = 0;
  let normalSignals = 0;

  for (const word of words) {
    if (word.length >= 2) {
      // Standard Arabic prefixes and suffixes
      if (word.startsWith('ال') || word.startsWith('وال') || word.startsWith('بال')) normalSignals++;
      if (word.endsWith('لا') || word.endsWith('لاو')) reversedSignals++;
      // Terminal letters appearing at the beginning indicates reverse order
      if (word.startsWith('ة') || word.startsWith('ى')) reversedSignals++;
      if (word.endsWith('ة') || word.endsWith('ى')) normalSignals++;
    }
  }

  // If reversed signals strongly dominate, reverse characters within Arabic words
  if (reversedSignals > 1 && reversedSignals > normalSignals) {
    return words
      .map((w) => (/[\u0600-\u06FF]/.test(w) ? w.split('').reverse().join('') : w))
      .reverse()
      .join(' ');
  }

  return normalized;
}

// ----------------------------------------------------------------------
// 4. Line Clustering per Page
// ----------------------------------------------------------------------

export function clusterItemsIntoLines(items: PdfTextItem[]): PdfLine[] {
  if (items.length === 0) return [];

  // Sort items by Y position ascending (top to bottom)
  const sorted = [...items].sort((a, b) => a.y - b.y);
  const lines: PdfLine[] = [];

  for (const item of sorted) {
    // Dynamic tolerance: items on the same line typically have delta Y <= 4-6px
    const tolerance = Math.max(4, (item.height || 10) * 0.45);
    let matchedLine = lines.find((l) => l.page === item.page && Math.abs(l.y - item.y) <= tolerance);

    if (!matchedLine) {
      matchedLine = {
        page: item.page,
        y: item.y,
        items: [],
      };
      lines.push(matchedLine);
    } else {
      // Update line Y with running average to prevent drift
      matchedLine.y = (matchedLine.y * matchedLine.items.length + item.y) / (matchedLine.items.length + 1);
    }

    matchedLine.items.push(item);
  }

  // Sort lines by page then Y ascending
  lines.sort((a, b) => (a.page !== b.page ? a.page - b.page : a.y - b.y));

  // Sort items within each line by X ascending (left to right)
  for (const line of lines) {
    line.items.sort((a, b) => a.x - b.x);
  }

  return lines;
}

